import { SHOTS } from "./paths.mjs";
import { chromium } from "playwright";

const base = process.env.KARASU_URL || "http://127.0.0.1:8765";
const out = SHOTS;
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const logs = [];
page.on("console", (m) => logs.push(`${m.type()}: ${m.text()}`));
page.on("pageerror", (e) => logs.push(`pageerror: ${e.message}`));
page.on("response", (r) => r.url().includes("/api/audio/") && logs.push(`audio ${r.status()} ${r.url().split("/api/")[1]}`));
await page.goto(`${base}/#/playlist/lane%3Afresh`, { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await page.getByRole("button", { name: "Play", exact: true }).first().click();
await page.waitForTimeout(3500);
const state = await page.evaluate(() => JSON.parse(localStorage.getItem("cd-player") || "{}").state);
console.log("queue", state?.queue?.length, "index", state?.index);
console.log((await page.locator("body").innerText()).split("\n").filter((l) => /Preview|Nothing playing/.test(l)).slice(0, 3));
await page.screenshot({ path: `${out}/desktop-playing.png` });
await page.locator("button[aria-label='Open Now Playing']").click();
await page.waitForTimeout(2000);
await page.screenshot({ path: `${out}/desktop-nowplaying.png` });
await page.keyboard.press("Escape");
await page.waitForTimeout(800);
await page.locator("button[aria-label='Queue']").first().click();
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/desktop-queue.png` });
console.log(logs.slice(-12).join("\n"));
await browser.close();
